import { randomUUID } from "node:crypto";
import { existsSync } from "node:fs";
import path from "node:path";
import { createClient, type SupabaseClient } from "@supabase/supabase-js";
import { afterAll, beforeAll, describe, expect, it } from "vitest";

/**
 * TESTS THAT REQUIRE A REAL SUPABASE
 *
 * These tests connect to a real Supabase project (Auth, PostgREST, Storage) and cover what the embedded Postgres tests
 * under tests/db CANNOT VERIFY: RLS with a real JWT, storage policies,
 * signed upload URLs and bucket limits.
 *
 * Run with:  npm run test:supabase
 * Required environment variables: SUPABASE_TEST_URL, SUPABASE_TEST_PUBLISHABLE_KEY, SUPABASE_TEST_SECRET_KEY
 * (read from the .env.local file in the project root; an already defined environment variable takes precedence).
 * The app's own variables (NEXT_PUBLIC_SUPABASE_URL …) are DELIBERATELY not used: which project the tests
 * run against must be written separately and explicitly.
 *
 * WARNING: Use a SEPARATE test project. The tests create users and applications and delete them at the end;
 *        do NOT RUN them against the production project. The migrations must already be applied to the project.
 */

const envFile = path.resolve(import.meta.dirname, "../../.env.local");
if (existsSync(envFile)) process.loadEnvFile(envFile);

const url = process.env.SUPABASE_TEST_URL;
const publishableKey = process.env.SUPABASE_TEST_PUBLISHABLE_KEY;
const secretKey = process.env.SUPABASE_TEST_SECRET_KEY;
const configured = Boolean(url && publishableKey && secretKey);

const BUCKET = "application-files";
const PASSWORD = `Test-${randomUUID()}-9a`;
const PDF = new Uint8Array([0x25, 0x50, 0x44, 0x46, 0x2d, 0x31, 0x2e, 0x37, 0x0a, 0x25, 0x45, 0x4f, 0x46]);

describe.skipIf(!configured)("Supabase integration (real project)", () => {
  let admin: SupabaseClient;
  let alice: SupabaseClient;
  let bob: SupabaseClient;
  let aliceId = "";
  let bobId = "";
  let aliceApp = "";
  const createdUsers: string[] = [];
  const createdObjects: string[] = [];

  const options = { auth: { persistSession: false, autoRefreshToken: false } };

  async function createUser(label: string, metadata: Record<string, unknown>) {
    const email = `test-${label}-${randomUUID()}@example.com`;
    const { data, error } = await admin.auth.admin.createUser({ email, password: PASSWORD, email_confirm: true, user_metadata: metadata });
    if (error || !data.user) throw new Error(`Test kullanıcısı oluşturulamadı: ${error?.message}`);
    createdUsers.push(data.user.id);
    // The session is opened through a path that needs no CAPTCHA (a one-time link token generated by the admin API): with
    // CAPTCHA enabled in Supabase, password sign-in without a token is rejected.
    const link = await admin.auth.admin.generateLink({ type: "magiclink", email });
    if (link.error || !link.data.properties?.hashed_token) throw new Error(`Test kullanıcısı için giriş bağlantısı üretilemedi: ${link.error?.message}`);
    const client = createClient(url!, publishableKey!, options);
    const signIn = await client.auth.verifyOtp({ type: "magiclink", token_hash: link.data.properties.hashed_token });
    if (signIn.error || !signIn.data.session) throw new Error(`Test kullanıcısı giriş yapamadı: ${signIn.error?.message}`);
    return { client, id: data.user.id };
  }

  beforeAll(async () => {
    admin = createClient(url!, secretKey!, options);
    const a = await createUser("alice", { first_name: "Alice", last_name: "Test", role: "staff" });
    const b = await createUser("bob", { first_name: "Bob", last_name: "Test" });
    alice = a.client;
    aliceId = a.id;
    bob = b.client;
    bobId = b.id;
    const { data, error } = await alice.from("applications").insert({ customer_id: aliceId }).select("id").single();
    if (error) throw new Error(`Başvuru oluşturulamadı: ${error.message}`);
    aliceApp = data.id as string;
  });

  afterAll(async () => {
    if (!configured) return;
    // Cleanup errors are never ignored silently: if a test user, application or file is left behind, it must be visible.
    const problems: string[] = [];
    if (createdObjects.length > 0) {
      const { error } = await admin.storage.from(BUCKET).remove(createdObjects);
      if (error) problems.push(`dosyalar: ${error.message}`);
    }
    if (createdUsers.length > 0) {
      const { error } = await admin.from("applications").delete().in("customer_id", createdUsers);
      if (error) problems.push(`başvurular: ${error.message}`);
    }
    for (const id of createdUsers) {
      const { error } = await admin.auth.admin.deleteUser(id);
      if (error) problems.push(`kullanıcı ${id}: ${error.message}`);
    }
    if (problems.length > 0) throw new Error(`Test verisi temizlenemedi: ${problems.join("; ")}`);
  });

  it("'role' in the sign-up metadata is ignored; a new user becomes a customer", async () => {
    const { data } = await admin.from("profiles").select("role, first_name").eq("id", aliceId).single();
    expect(data).toMatchObject({ role: "customer", first_name: "Alice" });
  });

  it("a customer cannot see another customer's application or form data", async () => {
    await alice.from("application_form_sections").insert({ application_id: aliceApp, section_id: "personal", data: { firstName: "Alice" } });
    const apps = await bob.from("applications").select("id").eq("id", aliceApp);
    expect(apps.error).toBeNull();
    expect(apps.data).toEqual([]);
    const sections = await bob.from("application_form_sections").select("section_id").eq("application_id", aliceApp);
    expect(sections.data).toEqual([]);
    const own = await alice.from("applications").select("id").eq("id", aliceApp);
    expect(own.data).toHaveLength(1);
  });

  it("a customer cannot change the status and payment fields", async () => {
    const result = await alice.from("applications").update({ payment_status: "verified" }).eq("id", aliceApp).select("id");
    expect(result.error).not.toBeNull();
    const { data } = await admin.from("applications").select("status, payment_status").eq("id", aliceApp).single();
    expect(data).toEqual({ status: "draft", payment_status: "not_due" });
  });

  it("a customer cannot use service role functions or internal notes", async () => {
    const rpc = await alice.rpc("svc_set_staff_access", { p_actor_id: aliceId, p_user_id: aliceId, p_role: "staff", p_is_active: true });
    expect(rpc.error).not.toBeNull();
    const notes = await alice.from("staff_notes").select("id");
    expect(notes.data ?? []).toEqual([]);
    const audit = await alice.from("audit_log").select("id");
    expect(audit.data ?? []).toEqual([]);
  });

  it("an anonymous client cannot access any application data", async () => {
    const anon = createClient(url!, publishableKey!, options);
    const result = await anon.from("applications").select("id");
    expect(result.data ?? []).toEqual([]);
  });

  it("the bucket is private: a file cannot be accessed through a public address", async () => {
    const path = `${aliceApp}/${randomUUID()}.pdf`;
    const upload = await admin.storage.from(BUCKET).upload(path, PDF, { contentType: "application/pdf" });
    expect(upload.error).toBeNull();
    createdObjects.push(path);
    const publicUrl = admin.storage.from(BUCKET).getPublicUrl(path).data.publicUrl;
    const response = await fetch(publicUrl);
    expect(response.ok).toBe(false);
  });

  it("a customer can only download files in their own application folder", async () => {
    const path = `${aliceApp}/${randomUUID()}.pdf`;
    await admin.storage.from(BUCKET).upload(path, PDF, { contentType: "application/pdf" });
    createdObjects.push(path);

    const own = await alice.storage.from(BUCKET).download(path);
    expect(own.error).toBeNull();
    expect(new Uint8Array(await own.data!.arrayBuffer())).toEqual(PDF);

    const foreign = await bob.storage.from(BUCKET).download(path);
    expect(foreign.error).not.toBeNull();
    const signed = await bob.storage.from(BUCKET).createSignedUrl(path, 60);
    expect(signed.error).not.toBeNull();
  });

  it("a customer cannot upload to, change or delete in storage directly", async () => {
    const path = `${aliceApp}/${randomUUID()}.pdf`;
    const direct = await alice.storage.from(BUCKET).upload(path, PDF, { contentType: "application/pdf" });
    expect(direct.error).not.toBeNull();

    const existing = `${aliceApp}/${randomUUID()}.pdf`;
    await admin.storage.from(BUCKET).upload(existing, PDF, { contentType: "application/pdf" });
    createdObjects.push(existing);
    await alice.storage.from(BUCKET).remove([existing]);
    const still = await admin.storage.from(BUCKET).download(existing);
    expect(still.error).toBeNull();
  });

  it("uploading through the signed URL issued by the server works and only allows that path", async () => {
    const path = `${aliceApp}/${randomUUID()}.pdf`;
    const signed = await admin.storage.from(BUCKET).createSignedUploadUrl(path);
    expect(signed.error).toBeNull();
    // For Blob bodies, storage reads the type from the Blob's own `type`, not from the `contentType` option;
    // a Blob without a type counts as "application/octet-stream" and is rejected by the bucket.
    const upload = await alice.storage
      .from(BUCKET)
      .uploadToSignedUrl(signed.data!.path, signed.data!.token, new Blob([PDF], { type: "application/pdf" }), { contentType: "application/pdf" });
    expect(upload.error).toBeNull();
    createdObjects.push(path);
    const check = await admin.storage.from(BUCKET).download(path);
    expect(new Uint8Array(await check.data!.arrayBuffer())).toEqual(PDF);
  });

  it("the bucket rejects a disallowed file type", async () => {
    const path = `${aliceApp}/${randomUUID()}.pdf`;
    const signed = await admin.storage.from(BUCKET).createSignedUploadUrl(path);
    const upload = await alice.storage
      .from(BUCKET)
      .uploadToSignedUrl(signed.data!.path, signed.data!.token, new Blob(["<html></html>"], { type: "text/html" }), { contentType: "text/html" });
    expect(upload.error).not.toBeNull();
  });

  it("an application cannot move to review before the payment is verified (service role included)", async () => {
    const result = await admin.from("applications").update({ status: "in_review", submitted_at: new Date().toISOString() }).eq("id", aliceApp).select("id");
    expect(result.error?.message ?? "").toContain("payment_not_verified");
  });

  it("Bob's identity cannot run the document sync function for Alice's application", async () => {
    const result = await bob.rpc("sync_application_documents", { p_application_id: aliceApp });
    expect(result.error).not.toBeNull();
    expect(bobId).not.toBe(aliceId);
  });
});

describe.skipIf(configured)("Supabase entegrasyonu", () => {
  it("SKIPPED because the SUPABASE_TEST_* variables are not set (not verified)", () => {
    expect(configured).toBe(false);
  });
});
